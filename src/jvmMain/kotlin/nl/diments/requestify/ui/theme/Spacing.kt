package nl.diments.requestify.ui.theme

import androidx.compose.ui.unit.dp

/**
 * The app's spacing scale: every padding and gap on the screens comes from here. Pages keep [xl] from the rail,
 * the title bar and the window's edges, and between Home's panes; sections inside a pane are [l] apart; a label
 * sits [s] above its control.
 */
object Spacing {
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
}
